package com.asc.common.data.message.repository;

import static org.assertj.core.api.Assertions.assertThat;

import com.asc.common.data.dialect.DatabaseDialect;
import java.nio.charset.StandardCharsets;
import org.junit.jupiter.api.AfterAll;
import org.junit.jupiter.api.BeforeAll;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.jdbc.datasource.DriverManagerDataSource;
import org.testcontainers.junit.jupiter.Testcontainers;
import org.testcontainers.postgresql.PostgreSQLContainer;

/**
 * Runs the PostgreSQL statements of the pending-message queue on a real PostgreSQL, with the column
 * types the EF migrations give {@code identity_pending_messages} there and the {@code
 * stringtype=unspecified} connection the services use. On a live stack they run only when the
 * broker refuses a message.
 */
@Testcontainers(disabledWithoutDocker = true)
class JdbcPendingMessageRepositoryPostgreSqlIT {
  private static PostgreSQLContainer postgres;
  private static JdbcPendingMessageRepository repository;
  private static JdbcTemplate jdbcTemplate;

  @BeforeAll
  static void start() {
    postgres = new PostgreSQLContainer("postgres:17");
    postgres.start();
    jdbcTemplate =
        new JdbcTemplate(
            new DriverManagerDataSource(
                postgres.getJdbcUrl() + "&stringtype=unspecified",
                postgres.getUsername(),
                postgres.getPassword()));
    jdbcTemplate.execute(
        """
        CREATE EXTENSION IF NOT EXISTS citext;
        CREATE TABLE identity_pending_messages (
          id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
          exchange_name citext NOT NULL,
          routing_key citext NOT NULL,
          headers citext NULL,
          body bytea NOT NULL,
          attempts integer NOT NULL,
          deliver_at timestamptz NOT NULL,
          created_at timestamptz NOT NULL);
        """);
    repository = new JdbcPendingMessageRepository(jdbcTemplate, DatabaseDialect.POSTGRESQL);
  }

  @AfterAll
  static void stop() {
    if (postgres != null) postgres.stop();
  }

  @BeforeEach
  void clean() {
    jdbcTemplate.update("DELETE FROM identity_pending_messages");
  }

  @Test
  void savedMessage_IsDueAtOnce_AndNotAfterItIsPostponed() {
    var body = "payload".getBytes(StandardCharsets.UTF_8);
    repository.save("exchange", "key", "{\"h\":1}", body);

    var due = repository.findDue(10);
    assertThat(due).hasSize(1);
    var message = due.getFirst();
    assertThat(message.exchange()).isEqualTo("exchange");
    assertThat(message.routingKey()).isEqualTo("key");
    assertThat(message.headers()).isEqualTo("{\"h\":1}");
    assertThat(message.body()).isEqualTo(body);
    assertThat(message.attempts()).isZero();
    assertThat(message.ageSeconds()).isBetween(0L, 60L);

    repository.postpone(message.id(), 3600);
    assertThat(repository.findDue(10)).isEmpty();
    var deliverIn =
        jdbcTemplate.queryForObject(
            "SELECT EXTRACT(EPOCH FROM deliver_at - now()) FROM identity_pending_messages",
            Double.class);
    assertThat(deliverIn).isBetween(3500.0, 3600.0);
    assertThat(
            jdbcTemplate.queryForObject(
                "SELECT attempts FROM identity_pending_messages", Integer.class))
        .isEqualTo(1);

    assertThat(repository.count()).isEqualTo(1);
    repository.delete(message.id());
    assertThat(repository.count()).isZero();
  }

  @Test
  void ageSeconds_CountsWholeSecondsSinceTheMessageWasCreated() {
    jdbcTemplate.update(
        "INSERT INTO identity_pending_messages (exchange_name, routing_key, headers, body,"
            + " attempts, deliver_at, created_at) VALUES ('e', 'k', NULL, '\\x00', 2,"
            + " now() - interval '1 minute', now() - interval '90.6 seconds')");

    var message = repository.findDue(10).getFirst();
    assertThat(message.ageSeconds()).isEqualTo(90);
    assertThat(message.attempts()).isEqualTo(2);
  }
}

namespace ASC.Core.Common.Security;

/// <summary>
/// Reads an image downloaded from an address someone else chose without taking in more than the size limit: a response without a length, or with a
/// wrong one, is cut off at the limit instead of being buffered whole.
/// </summary>
public static class LimitedImageReader
{
    /// <summary>The bytes of the body, or null when the body is longer than <paramref name="limit"/>.</summary>
    public static async Task<byte[]> ReadAsync(HttpContent content, long limit, CancellationToken cancellationToken = default)
    {
        if (content.Headers.ContentLength > limit)
        {
            return null;
        }

        await using var stream = await content.ReadAsStreamAsync(cancellationToken);
        using var buffer = new MemoryStream();
        var chunk = new byte[81920];

        int read;
        while ((read = await stream.ReadAsync(chunk, cancellationToken)) > 0)
        {
            if (buffer.Length + read > limit)
            {
                return null;
            }

            buffer.Write(chunk, 0, read);
        }

        return buffer.ToArray();
    }
}

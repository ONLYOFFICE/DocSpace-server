namespace ASC.Core.Common.Tests;

/// <summary>
/// What Swashbuckle writes into the success responses before <see cref="SwaggerSuccessApiResponseFilter"/> sees them,
/// and that the filter wraps them. The filter rests on two things the generator does: it writes each response content
/// as a concrete <see cref="OpenApiMediaType"/> (the filter skips any other <c>IOpenApiMediaType</c>), and it writes
/// a <c>JsonElement?</c> payload as an empty schema (the filter documents that one as any JSON value, not as an object).
/// The documents are generated by the real SwaggerGen over a controller of this file, with the filter on and off.
/// </summary>
public class SwaggerSuccessApiResponseFilterTests
{
    [Fact]
    public void Generator_WritesEverySuccessContentAsAConcreteMediaType()
    {
        var document = Generate(withFilter: false);

        foreach (var path in new[] { "/probe/any", "/probe/dto" })
        {
            var content = document.Paths[path].Operations![HttpMethod.Get].Responses!["200"].Content!;

            content.Should().NotBeEmpty();
            content.Values.Should().AllBeOfType<OpenApiMediaType>();
        }
    }

    [Fact]
    public void Generator_WritesAJsonElementPayloadAsAnEmptySchema()
    {
        var document = Generate(withFilter: false);

        var schema = document.Paths["/probe/any"].Operations![HttpMethod.Get].Responses!["200"].Content!.Values.First().Schema;

        var empty = schema.Should().BeOfType<OpenApiSchema>().Subject;
        empty.Type.Should().BeNull();
        empty.Properties.Should().BeNullOrEmpty();
        empty.Items.Should().BeNull();
        empty.OneOf.Should().BeNullOrEmpty();
        empty.AllOf.Should().BeNullOrEmpty();
        empty.AnyOf.Should().BeNullOrEmpty();
        empty.Format.Should().BeNull();
    }

    [Fact]
    public void Filter_WrapsAJsonElementPayloadAsAnyJsonValue()
    {
        var document = Generate(withFilter: true);

        var schema = document.Paths["/probe/any"].Operations![HttpMethod.Get].Responses!["200"].Content!.Values.First().Schema;

        schema.Should().BeOfType<OpenApiSchemaReference>().Which.Reference.Id.Should().Be("JsonValueWrapper");
        var response = ((OpenApiSchema)document.Components!.Schemas!["JsonValueWrapper"]).Properties!["response"];
        response.Type.Should().BeNull();
    }

    [Fact]
    public void Filter_WrapsADtoPayloadInItsOwnWrapper()
    {
        var document = Generate(withFilter: true);

        var schema = document.Paths["/probe/dto"].Operations![HttpMethod.Get].Responses!["200"].Content!.Values.First().Schema;

        schema.Should().BeOfType<OpenApiSchemaReference>().Which.Reference.Id.Should().Be("SwaggerProbeWrapper");
        ((OpenApiSchema)document.Components!.Schemas!["SwaggerProbeWrapper"]).Properties!["response"]
            .Should().BeOfType<OpenApiSchemaReference>().Which.Reference.Id.Should().Be(nameof(SwaggerProbeDto));
    }

    private static Microsoft.OpenApi.OpenApiDocument Generate(bool withFilter)
    {
        var services = new ServiceCollection();
        services.AddLogging();
        services.AddSingleton<IWebHostEnvironment>(new ProbeEnvironment());
        services.AddMvcCore()
            .ConfigureApplicationPartManager(manager =>
            {
                // Only the probe controller: the test assembly is the entry assembly, and nothing else of it is a controller of this document.
                manager.ApplicationParts.Clear();
                manager.FeatureProviders.Add(new ProbeControllerFeatureProvider());
            })
            .AddApiExplorer();
        services.AddSwaggerGen(c =>
        {
            c.SwaggerDoc("v1", new OpenApiInfo { Title = "probe", Version = "v1" });
            if (withFilter)
            {
                c.DocumentFilter<SwaggerSuccessApiResponseFilter>();
            }
        });

        using var provider = services.BuildServiceProvider();

        return provider.GetRequiredService<ISwaggerProvider>().GetSwagger("v1");
    }

    private sealed class ProbeEnvironment : IWebHostEnvironment
    {
        public string ApplicationName { get; set; } = typeof(ProbeEnvironment).Assembly.GetName().Name!;
        public string EnvironmentName { get; set; } = "Production";
        public string ContentRootPath { get; set; } = AppContext.BaseDirectory;
        public IFileProvider ContentRootFileProvider { get; set; } = new NullFileProvider();
        public string WebRootPath { get; set; } = AppContext.BaseDirectory;
        public IFileProvider WebRootFileProvider { get; set; } = new NullFileProvider();
    }

    private sealed class ProbeControllerFeatureProvider : IApplicationFeatureProvider<ControllerFeature>
    {
        public void PopulateFeature(IEnumerable<ApplicationPart> parts, ControllerFeature feature)
        {
            feature.Controllers.Add(typeof(SwaggerProbeController).GetTypeInfo());
        }
    }
}

/// <summary>A payload with a schema of its own.</summary>
public class SwaggerProbeDto
{
    /// <summary>A value.</summary>
    public string? Name { get; set; }
}

[ApiController]
[Route("probe")]
internal sealed class SwaggerProbeController : ControllerBase
{
    [HttpGet("any")]
    public JsonElement? GetAny() => null;

    [HttpGet("dto")]
    public SwaggerProbeDto GetDto() => new();
}

namespace ASC.Webhooks.Core;

/// <summary>
/// The webhook contract (<c>Contract/docspace-webhooks.yaml</c>, generated by <c>common/Tools/ASC.Webhooks.Contract</c>)
/// as it is built into this assembly, for serving it next to the REST OpenAPI documents.
/// </summary>
public static class WebhookContract
{
    /// <summary>
    /// The name the document is listed under in Scalar and Swagger UI.
    /// </summary>
    public const string DocumentName = "docspace.webhooks";

    /// <summary>
    /// Where the document is served. Under <c>/openapi</c>, which the router passes to Web.Studio, and named after
    /// the contract's <c>info.version</c>, as the REST documents are named after theirs.
    /// </summary>
    public const string Route = "/openapi/docspace.webhooks/1.0.yaml";

    /// <summary>
    /// The media type the document is served with.
    /// </summary>
    public const string ContentType = "application/yaml; charset=utf-8";

    private const string ResourceName = "ASC.Webhooks.Core.Contract.docspace-webhooks.yaml";

    /// <summary>
    /// A new stream over the contract; the caller disposes it.
    /// </summary>
    public static Stream OpenRead()
    {
        return typeof(WebhookContract).Assembly.GetManifestResourceStream(ResourceName)
            ?? throw new InvalidOperationException($"The webhook contract is not embedded as {ResourceName}.");
    }
}

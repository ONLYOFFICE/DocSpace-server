namespace ASC.Webhooks.Contract;

/// <summary>
/// Builds <c>docspace-webhooks.yaml</c>, the contract the webhook SDKs are generated from.
/// </summary>
/// <remarks>
/// Only what the code cannot say is written by hand, in <see cref="ContractHeader"/>: the serialization and
/// transport notes (with their numbers and header names read from <see cref="WebhookDelivery"/>), the
/// <see cref="SchemaBuilder.EntryIdSchema"/> schema and the description of the trigger map. Everything else is read
/// from the code: the trigger map from the trigger table below, the schemas from the payload DTOs and the envelope,
/// and their descriptions from the XML documentation of each type and property.
/// </remarks>
public static class WebhookContractGenerator
{
    /// <summary>
    /// The generated contract the webhook SDKs are built from.
    /// </summary>
    public const string ContractFileName = "docspace-webhooks.yaml";

    private const string GeneratedComment =
        "Generated by common/Tools/ASC.Webhooks.Contract from the webhook payload DTOs, WebhookTrigger and\n" +
        "WebhookDelivery. Do not edit: change those and run\n" +
        "dotnet run --project common/Tools/ASC.Webhooks.Contract";

    /// <summary>
    /// The payload each trigger family sends; the family is the part of the trigger name before the first dot.
    /// </summary>
    /// <remarks>
    /// The table lives here rather than on <see cref="WebhookTrigger"/> because the DTOs sit in assemblies above
    /// ASC.Webhooks.Core and cannot be named from it. A trigger of a family missing here stops the generator.
    /// </remarks>
    private static readonly Dictionary<string, Type> _payloadsByFamily = new()
    {
        ["user"] = typeof(UserWebhookDto),
        ["group"] = typeof(GroupWebhookDto),
        ["file"] = typeof(FileWebhookDto<>),
        ["folder"] = typeof(FolderWebhookDto<>),
        ["room"] = typeof(RoomWebhookDto<>),
        // an agent is an AI room and has the same shape today
        ["agent"] = typeof(RoomWebhookDto<>)
    };

    /// <summary>
    /// The triggers whose payload is not their family's: the form family has none of its own.
    /// </summary>
    private static readonly Dictionary<WebhookTrigger, Type> _payloadsByTrigger = new()
    {
        [WebhookTrigger.FormSubmit] = typeof(FormSubmitWebhookDto<>),
        [WebhookTrigger.FormFilledOut] = typeof(FileWebhookDto<>),
        [WebhookTrigger.FormStopped] = typeof(FileWebhookDto<>)
    };

    /// <summary>
    /// The directory of the contract, found by walking up from <paramref name="start"/> to the
    /// repository root.
    /// </summary>
    public static string FindContractDirectory(string start)
    {
        for (var directory = new DirectoryInfo(start); directory != null; directory = directory.Parent)
        {
            if (File.Exists(Path.Combine(directory.FullName, "ASC.Web.slnx")))
            {
                return Path.Combine(directory.FullName, "common", "ASC.Webhooks.Core", "Contract");
            }
        }

        throw new DirectoryNotFoundException($"No ASC.Web.slnx above {start}: run the generator from the server repository.");
    }

    /// <summary>
    /// The contract, as LF-terminated YAML.
    /// </summary>
    /// <exception cref="InvalidOperationException">A payload member has no summary, or a trigger has no payload in
    /// the trigger table.</exception>
    public static string Generate()
    {
        var options = WebhookPublisher.CreateSerializerOptions(null);
        options.MakeReadOnly(true);

        var assemblies = _payloadsByFamily.Values
            .Concat(_payloadsByTrigger.Values)
            .Append(typeof(WebhookPayload<,>))
            .Select(t => t.Assembly);

        var schemas = new SchemaBuilder(options, new XmlDocumentation(assemblies));

        schemas.Add(typeof(WebhookPayload<,>));

        var triggerMap = new YamlMappingNode();
        var webhooks = new YamlMappingNode();
        var families = new List<string>();

        // the payload schemas in the order the triggers first use them, each with its delivery schema
        var payloadSchemas = new List<string>();

        // Every trigger in the order the portal lists them; the catch-all, which carries no payload of its own, goes
        // last with null and is not a webhook of its own.
        var triggers = Enum.GetValues<WebhookTrigger>()
            .OrderBy(t => t == WebhookTrigger.All)
            .ThenBy(t => t.GetOrder())
            .ThenBy(t => t);

        foreach (var trigger in triggers)
        {
            if (trigger == WebhookTrigger.All)
            {
                triggerMap.Add(trigger.ToCustomString(), new YamlScalarNode("null") { Style = ScalarStyle.Plain });
                continue;
            }

            var payloadSchema = schemas.Add(GetPayloadType(trigger));

            triggerMap.Add(trigger.ToCustomString(), payloadSchema);
            webhooks.Add(trigger.ToCustomString(), ContractHeader.GetWebhook(trigger, payloadSchema));

            if (!payloadSchemas.Contains(payloadSchema))
            {
                payloadSchemas.Add(payloadSchema);
            }

            if (!families.Contains(trigger.GetTargetType()))
            {
                families.Add(trigger.GetTargetType());
            }
        }

        if (schemas.Undocumented.Count > 0)
        {
            throw new InvalidOperationException(
                "These webhook payload members have no <summary>, which is their description in the contract:\n  " +
                string.Join("\n  ", schemas.Undocumented));
        }

        var root = ContractHeader.Build();

        ((YamlMappingNode)root[ContractHeader.TriggerMapKey]).Add("map", triggerMap);

        var tags = (YamlSequenceNode)root["tags"];

        foreach (var family in families)
        {
            tags.Add(ContractHeader.GetTag(family));
        }

        var webhookEntries = (YamlMappingNode)root["webhooks"];

        foreach (var (name, webhook) in webhooks)
        {
            webhookEntries.Add(name, webhook);
        }

        var componentSchemas = (YamlMappingNode)root["components"]["schemas"];

        foreach (var (name, schema) in schemas.Schemas)
        {
            componentSchemas.Add(name, schema);
        }

        foreach (var payloadSchema in payloadSchemas)
        {
            componentSchemas.Add(ContractHeader.GetDeliveryName(payloadSchema), ContractHeader.GetDeliverySchema(payloadSchema));
        }

        return ContractYamlWriter.Write(root, GeneratedComment);
    }

    private static Type GetPayloadType(WebhookTrigger trigger)
    {
        if (_payloadsByTrigger.TryGetValue(trigger, out var type) || _payloadsByFamily.TryGetValue(trigger.GetTargetType(), out type))
        {
            return type;
        }

        throw new InvalidOperationException(
            $"No payload for the trigger {trigger.ToCustomString()}: add its family or the trigger itself to the trigger table in {nameof(WebhookContractGenerator)}.");
    }
}
